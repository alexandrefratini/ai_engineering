const { chromium } = require("/opt/node-tools/node_modules/playwright");
const [, , cookie, out] = process.argv;
(async () => {
  const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
  const c = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: "fr-CA", timezoneId: "America/Toronto" });
  await c.addCookies([{ name: "crm.session_token", value: cookie, domain: "localhost", path: "/" }]);
  const p = await c.newPage();
  const errors = [];
  p.on("pageerror", (e) => errors.push("page: " + e.message.slice(0, 200)));
  p.on("console", (m) => m.type() === "error" && !m.text().includes("Failed to load resource") && errors.push("console: " + m.text().slice(0, 200)));
  await p.goto("http://localhost:3000/crm/real-estate/leads", { waitUntil: "networkidle" });
  await p.addStyleTag({ content: "nextjs-portal{display:none!important}" });
  console.log("avant:", (await p.locator("h1").first().innerText()).split("\n")[0]);
  await p.locator('[data-slot="translate-trigger"]').click();
  await p.getByRole("menuitemradio", { name: "Español" }).click();
  await p.getByRole("button", { name: /Traduire en/ }).click();
  await p.waitForLoadState("load");
  await p.waitForTimeout(9000);
  console.log("après (es):", (await p.locator("h1").first().innerText()).split("\n")[0]);
  console.log("table:", (await p.locator("th").allInnerTexts()).slice(0, 4).join(" | "));
  await p.screenshot({ path: `${out}/trad-es-1.png` });
  await p.locator("nav a").nth(2).click();
  await p.waitForTimeout(9000);
  console.log("navigation SPA ->", p.url(), "|", (await p.locator("h1").first().innerText()).split("\n")[0]);
  await p.getByRole("textbox").first().fill("karim").catch(() => {});
  await p.screenshot({ path: `${out}/trad-es-2.png` });
  const active = await p.locator('[data-slot="translate-trigger"][data-active]').count();
  console.log("bouton traduction actif:", active);
  await p.locator('[data-slot="translate-trigger"]').click();
  await p.getByRole("menuitemradio", { name: /Français/ }).click();
  await p.waitForLoadState("load");
  await p.waitForTimeout(3000);
  console.log("retour:", (await p.locator("h1").first().innerText()).split("\n")[0], "| cookies googtrans:", (await c.cookies()).filter((x) => x.name === "googtrans").length);
  console.log("erreurs:", errors.length ? errors : "aucune");
  await b.close();
})();
