const { chromium } = require("/opt/node-tools/node_modules/playwright");
const [, , cookie, out] = process.argv;
(async () => {
  const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
  const c = await b.newContext({ viewport: { width: 1440, height: 800 }, locale: "fr-CA", timezoneId: "America/Toronto" });
  await c.addCookies([{ name: "crm.session_token", value: cookie, domain: "localhost", path: "/" }]);
  const p = await c.newPage();
  const errors = [];
  const requests = [];
  p.on("pageerror", (e) => errors.push(e.message.slice(0, 200)));
  p.on("console", (m) => m.type() === "error" && errors.push("console: " + m.text().slice(0, 160)));
  p.on("request", (r) => r.url().includes("translate.google") && requests.push(r.url().slice(0, 90)));
  await p.goto("http://localhost:3000/crm", { waitUntil: "networkidle" });
  await p.addStyleTag({ content: "nextjs-portal{display:none!important}" });
  await p.getByRole("button", { name: "Traduire la page" }).click();
  await p.waitForTimeout(500);
  await p.screenshot({ path: `${out}/trad-1.png` });
  await p.getByRole("menuitemradio", { name: "English" }).click();
  await p.waitForTimeout(600);
  await p.screenshot({ path: `${out}/trad-2.png` });
  await p.getByRole("button", { name: "Traduire en English" }).click();
  await p.waitForLoadState("load");
  await p.waitForTimeout(3500);
  const cookies = (await c.cookies()).filter((x) => x.name === "googtrans");
  console.log("cookie:", JSON.stringify(cookies.map((x) => x.value)));
  console.log("requetes google:", requests);
  console.log("bouton actif:", await p.getByRole("button", { name: /Traduction active/ }).count());
  await p.screenshot({ path: `${out}/trad-3.png` });
  console.log("erreurs:", errors.length ? errors : "aucune");
  await b.close();
})();
